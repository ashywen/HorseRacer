package horseracer.model;

/**
 * Represents the difficulty levels available in the game.
 * <p>
 * Each difficulty level determines how challenging the gameplay will be,
 * such as obstacle speed, frequency, or other game mechanics.
 *
 *
 * @author Kathy Yao
 * @version 1.0.0
 */
public enum Difficulty {

    /** Easy difficulty level with minimal challenge. */
    EASY,

    /** Medium difficulty level with moderate challenge. */
    MEDIUM,

    /** Hard difficulty level with high challenge. */
    HARD
}